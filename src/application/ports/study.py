"""参加者管理が要求する保存・再生・比較計画のポート。"""

from collections.abc import Callable
from datetime import datetime
from pathlib import Path
from typing import Protocol

from src.domain.catalog import PlaybackAvailability, PlaybackContext

Clock = Callable[[], datetime]


class Playback(Protocol):
    def availability(self, context: PlaybackContext, now: datetime) -> PlaybackAvailability: ...
    def file(self, context: PlaybackContext, now: datetime) -> Path: ...
    def resolve(self, context: PlaybackContext, now: datetime) -> dict | None: ...


class ParticipantRepository(Protocol):
    def add_participant(self, participant_id, identity_key, expires_at): ...
    def participant(self, participant_id, now) -> dict | None: ...
    def participant_by_identity(self, identity_key, now) -> str | None: ...
    def bind_identity(self, participant_id, identity_key, now) -> bool: ...


class SessionRepository(ParticipantRepository, Protocol):
    def assign(self, plan, participant_id, context, now): ...
    def freeze_assignment(self, plan, participant_id, inputs, now): ...
    def analysis_snapshot(self, now): ...
    def purge(self, now): ...
    def get(self, token_hash, now) -> dict | None: ...
    def put(self, token_hash, payload): ...
    def active_session(self, participant_id, context, now): ...
    def rekey(self, previous, replacement): ...
    def delete(self, token_hash): ...
    def delete_participant(self, participant_id): ...
