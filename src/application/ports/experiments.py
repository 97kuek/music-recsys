"""Experiment workflows depend on these contracts, not storage or model libraries."""

from collections.abc import Callable
from contextlib import AbstractContextManager
from dataclasses import dataclass
from pathlib import Path
from typing import Protocol

from src.domain.experiments import ConditionResult, ProgressSnapshot


@dataclass(frozen=True)
class EvaluationOptions:
    model_cache: Path | None = None
    export_path: Path | None = None
    model_version: str | None = None
    phase: str = "validation"
    gpu_popularity: bool = False
    gpu_itemcf: bool = False
    als_backend: str | None = None
    ease_memory_budget_mb: float | None = None


class EvaluationSession(Protocol):
    @property
    def output(self) -> Path: ...
    def train(self) -> None: ...
    def score(self) -> dict: ...
    def render(self, result: dict) -> None: ...
    def verify(self) -> None: ...
    def export(self, result: dict) -> None: ...
    def publish(self, result: dict) -> None: ...


class EvaluationBackend(Protocol):
    def open(
        self, source: object, options: EvaluationOptions
    ) -> AbstractContextManager[EvaluationSession]: ...


class StudySession(Protocol):
    @property
    def output(self) -> Path: ...
    @property
    def conditions(self) -> tuple[str, ...]: ...
    @property
    def complete(self) -> bool: ...
    def check_space(self, minimum_free_gb: float) -> None: ...
    def completed(self, name: str) -> bool: ...
    def execute(self, name: str) -> None: ...
    def verify(self, name: str) -> dict: ...
    def evidence(self, name: str, result: dict) -> ConditionResult: ...
    def summarize(self, finished: list[tuple[str, dict]]) -> list[str]: ...
    def record(self, message: str) -> None: ...
    def checkpoint(self, state: ProgressSnapshot) -> None: ...


class StudyBackend(Protocol):
    def open(self, source: object) -> AbstractContextManager[StudySession]: ...


Render = Callable[[object, dict], None]


class SensitivitySession(Protocol):
    @property
    def output(self) -> Path: ...
    @property
    def complete(self) -> bool: ...
    @property
    def conditions(self) -> tuple[str, ...]: ...
    @property
    def batches(self) -> tuple[tuple[float, float], ...]: ...
    def batch_completed(self, batch: tuple[float, float]) -> bool: ...
    def execute_batch(self, batch: tuple[float, float]) -> None: ...
    def check_space(self, minimum_free_gb: float) -> None: ...
    def completed(self, name: str) -> bool: ...
    def execute(self, name: str) -> None: ...
    def verify(self, name: str) -> tuple[dict, dict]: ...
    def publish(self, finished: list[tuple[str, dict, dict]]) -> None: ...


class SensitivityBackend(Protocol):
    def open(self, source: object) -> AbstractContextManager[SensitivitySession]: ...
