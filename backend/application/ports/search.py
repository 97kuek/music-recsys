"""Resources required by smoke and budgeted search workflows."""

from collections.abc import Iterator
from contextlib import AbstractContextManager
from typing import Protocol

from backend.domain.search import SearchSnapshot, TrialOutcome, TrialSpec


class SearchSession(Protocol):
    @property
    def planned(self) -> int: ...
    @property
    def max_trials(self) -> int: ...
    @property
    def time_budget(self) -> float | None: ...
    @property
    def smoke_passed(self) -> bool: ...
    def prepare(self) -> None: ...
    def plans(self) -> Iterator[TrialSpec]: ...
    def execute(self, trial: TrialSpec) -> TrialOutcome: ...
    def checkpoint(self, state: SearchSnapshot) -> None: ...
    def result(self) -> dict: ...


class SearchBackend(Protocol):
    def open(self, config: object, *, smoke: bool) -> AbstractContextManager[SearchSession]: ...
